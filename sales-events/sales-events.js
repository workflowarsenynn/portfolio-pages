document.addEventListener("DOMContentLoaded", () => {
  renderSalesPdfExport();
  if (new URLSearchParams(window.location.search).get("pdf") === "1") {
    document.body.classList.add("pdf-mode");
  }

  document.querySelectorAll("[data-sales-case]").forEach((card) => {
    card.addEventListener("click", (event) => {
      if (event.target.closest("a") || event.target.closest("[data-lightbox-src]")) return;
      openSalesCase(card.dataset.salesCase);
    });
    card.addEventListener("keydown", (event) => {
      if (event.key !== "Enter" && event.key !== " ") return;
      if (event.target.closest("[data-lightbox-src]")) return;
      event.preventDefault();
      openSalesCase(card.dataset.salesCase);
    });
  });

  document.addEventListener("click", (event) => {
    const trigger = event.target.closest("[data-lightbox-src]");
    if (!trigger) return;
    event.preventDefault();
    event.stopPropagation();
    openSalesLightbox(trigger);
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeSalesLightbox();
      return;
    }
    if (event.key !== "Enter" && event.key !== " ") return;
    const trigger = event.target.closest("[data-lightbox-src]");
    if (!trigger) return;
    event.preventDefault();
    openSalesLightbox(trigger);
  });
});
