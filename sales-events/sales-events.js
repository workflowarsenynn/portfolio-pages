function closeSalesCase() {
  document.getElementById("sales-case-detail")?.classList.remove("open");
  document.querySelectorAll("[data-sales-case]").forEach((card) => card.classList.remove("active"));
}

function ensureSalesLightbox() {
  let lightbox = document.querySelector(".image-lightbox");
  if (lightbox) return lightbox;

  lightbox = document.createElement("div");
  lightbox.className = "image-lightbox";
  lightbox.setAttribute("aria-hidden", "true");
  lightbox.innerHTML = `
    <button class="lightbox-backdrop" type="button" aria-label="Закрыть изображение"></button>
    <figure class="lightbox-frame">
      <img src="" alt="">
      <figcaption></figcaption>
    </figure>
    <button class="lightbox-close" type="button" aria-label="Закрыть изображение">×</button>
  `;
  document.body.appendChild(lightbox);
  lightbox.querySelector(".lightbox-backdrop").addEventListener("click", closeSalesLightbox);
  lightbox.querySelector(".lightbox-close").addEventListener("click", closeSalesLightbox);
  return lightbox;
}

function openSalesLightbox(source) {
  const lightbox = ensureSalesLightbox();
  const image = lightbox.querySelector("img");
  const caption = lightbox.querySelector("figcaption");
  const src = source.dataset.lightboxSrc || source.getAttribute("src");
  const text = source.dataset.lightboxCaption || source.getAttribute("alt") || source.querySelector?.("figcaption")?.textContent || "";
  if (!src || !image || !caption) return;

  image.src = src;
  image.alt = source.getAttribute("alt") || text;
  caption.textContent = text;
  lightbox.classList.add("open");
  lightbox.setAttribute("aria-hidden", "false");
  document.body.classList.add("lightbox-open");
  lightbox.querySelector(".lightbox-close").focus({ preventScroll: true });
}

function closeSalesLightbox() {
  const lightbox = document.querySelector(".image-lightbox");
  if (!lightbox) return;
  lightbox.classList.remove("open");
  lightbox.setAttribute("aria-hidden", "true");
  document.body.classList.remove("lightbox-open");
}

